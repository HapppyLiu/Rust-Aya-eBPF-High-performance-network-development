//! CLAIM: 两个入参引用 + 引用返回值时省略规则不适用，编译器要求显式标注而非推断（E0106）。
//!
//! C-04：省略规则在两个入参引用时失效。
//!
//! 关注点：编译器此处**有能力**看出返回值来自 a 或 b，但它拒绝**猜**是哪一个 ——
//! 猜错的后果是悬垂引用，而两个候选之间没有可靠依据可分辨。
//! 加上 `<'a>` 并把两个入参都标成 `'a` 即可通过（见 `src/c04.rs::longest`）。

pub fn longest(a: &str, b: &str) -> &str {
    if a.len() >= b.len() { a } else { b }
}
